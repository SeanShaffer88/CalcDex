def machin_pi(prec):
    def atan_inv(n):
        x = D(1) / n; s = x; t = x; k = 1
        while abs(t) > D(10) ** (-prec - 5):
            t = -t / (n * n); k += 2; s += t / k
        return s
    return 4 * (4 * atan_inv(5) - atan_inv(239))

PI = machin_pi(165)

def r34(x):
    with localcontext() as c:
        c.prec = 34
        c.rounding = ROUND_HALF_EVEN
        return +x

def taylor_sin(x):
    t = x; s = x; k = 1
    while abs(t) > D(10) ** -160:
        t = -t * x * x / ((2 * k) * (2 * k + 1)); s += t; k += 1
    return s

def taylor_cos(x):
    t = D(1); s = D(1); k = 1
    while abs(t) > D(10) ** -160:
        t = -t * x * x / ((2 * k - 1) * (2 * k)); s += t; k += 1
    return s

def reduce(x):
    k = (x / (2 * PI)).to_integral_value()
    return x - k * 2 * PI

def sin(x): return taylor_sin(reduce(x))
def cos(x): return taylor_cos(reduce(x))
def tan(x): return sin(x) / cos(x)

def atan_series(x):
    t = x; s = x; k = 1
    while abs(t) > D(10) ** -160:
        t = -t * x * x; k += 2; s += t / k
    return s

def atan(x):
    neg = x < 0; a = abs(x)
    inv = a > 1
    if inv: a = 1 / a
    for _ in range(6):
        a = a / (1 + (1 + a * a).sqrt())
    r = atan_series(a) * 64
    if inv: r = PI / 2 - r
    return -r if neg else r

def asin(x):
    if abs(x) == 1: return PI / 2 * (1 if x > 0 else -1)
    return atan(x / (1 - x * x).sqrt())
def acos(x): return PI / 2 - asin(x)
def sinh(x): return (x.exp() - (-x).exp()) / 2
def cosh(x): return (x.exp() + (-x).exp()) / 2
def tanh(x): return sinh(x) / cosh(x)
def asinh(x):
    return (x + (x * x + 1).sqrt()).ln() if x >= 0 else -(((-x) + (x * x + 1).sqrt()).ln())
def acosh(x): return (x + (x * x - 1).sqrt()).ln()
def atanh(x): return ((1 + x) / (1 - x)).ln() / 2
def expm1(x): return x.exp() - 1
def ln1p(x): return (1 + x).ln()

